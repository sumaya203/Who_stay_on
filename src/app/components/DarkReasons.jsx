"use client";

import { CircleAlert, X, Info } from 'lucide-react';
import { Panel, Badge, EmptyState } from './ui';
import { fmtNumber, reasonTag } from './analytics';

/**
 * Every dark cell the engine returned, written out in the open — grouped by
 * hour, tagged by constraint, with the value the shop would have earned.
 * This is the touch/keyboard-safe companion to the roster's click-to-inspect.
 */
export default function DarkReasons({ model, onNavigate }) {
  const entries = [];
  for (const hour of model.outageHours) {
    for (const id of hour.dark) {
      const shop = model.shopStats.find((s) => s.id === id);
      entries.push({
        key: `${hour.t}:${id}`,
        hour,
        id,
        kw: shop?.kw ?? 0,
        reason: hour.reasonById?.[id] ?? '',
        forgone: shop?.perHourValue?.[hour.t] ?? 0,
      });
    }
  }

  const worstHour = model.outageHours.reduce(
    (best, h) => (!best || h.dark.length > best.dark.length ? h : best),
    null
  );

  const meta = (
    <>
      {entries.length ? (
        <Badge tone="amber">
          {entries.length} dark hour{entries.length === 1 ? '' : 's'}
        </Badge>
      ) : null}
      <Badge tone="mute">engine text, verbatim</Badge>
    </>
  );

  if (!entries.length) {
    return (
      <Panel id="dark-reasons" title="Dark Hours & Reasons" subtitle="Why each shop was shed" icon={CircleAlert} meta={meta}>
        <EmptyState
          icon={Info}
          title={model.solved ? 'Nothing was shed' : 'No explanations yet'}
          body={
            model.solved
              ? `Every shop stayed lit through all ${model.outageHours.length} outage hour${
                  model.outageHours.length === 1 ? '' : 's'
                }, so the engine reported no dark slots.`
              : 'Run the optimizer and each shed hour will be listed here with the engine’s own reasoning.'
          }
        />
      </Panel>
    );
  }

  const byHour = new Map();
  for (const entry of entries) {
    if (!byHour.has(entry.hour.t)) byHour.set(entry.hour.t, []);
    byHour.get(entry.hour.t).push(entry);
  }

  return (
    <Panel
      id="dark-reasons"
      title="Dark Hours & Reasons"
      subtitle={`${entries.length} shed shop-hours across ${byHour.size} hour${byHour.size === 1 ? '' : 's'} · worst ${worstHour?.label} (${worstHour?.dark.length} shed)`}
      icon={CircleAlert}
      bodyClass="space-y-2"
      meta={meta}
      footer={
        <>
          <span className="inline-flex items-center gap-1.5">
            <Info size={11} aria-hidden="true" />
            Each explanation is generated by the engine from the numbers behind it.
          </span>
          <span className="num">
            {fmtNumber(entries.reduce((sum, e) => sum + (e.forgone || 0), 0))} value forgone ·{' '}
            {fmtNumber(entries.reduce((sum, e) => sum + (e.kw || 0), 0))} kW never drawn
          </span>
        </>
      }
    >
      {[...byHour.entries()].map(([t, list]) => {
        const hour = model.outageHours.find((h) => h.t === t);
        return (
          <div key={t} className="rounded-[11px] border border-hairline bg-surface-2 p-2.5">
            <div className="mb-2 flex flex-wrap items-center gap-2 px-0.5">
              <span className="hour-badge" title={hour.range}>
                <span>{hour.label}</span>
                <span className="num font-medium normal-case tracking-normal text-ink-faint">
                  → {hour.range.split('–')[1]}
                </span>
              </span>
              <span className="text-[11px] text-ink-faint">
                {fmtNumber(hour.loadKw)} kW on the bus · {fmtNumber(hour.headroomKw)} kW spare ·{' '}
                {fmtNumber(hour.dark.length)} shed
              </span>
              <button
                type="button"
                className="btn btn-ghost btn-sm ml-auto"
                onClick={() => onNavigate?.('roster')}
                title="Find these cells in the roster"
              >
                Show in roster
              </button>
            </div>
            <ul className="space-y-1.5">
              {list.map((entry) => {
                const tag = reasonTag(entry.reason);
                return (
                  <li key={entry.key} className="reason-entry">
                    <span className="legend-swatch rc-off mt-0.5">
                      <X size={9} strokeWidth={3.4} aria-hidden="true" />
                    </span>
                    <div className="min-w-0 flex-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <span className="chip">{entry.id}</span>
                        <Badge tone={tag.tone}>{tag.label}</Badge>
                        <span className="num text-[10.5px] text-ink-faint">
                          {fmtNumber(entry.kw)} kW · {fmtNumber(entry.forgone)} value forgone
                        </span>
                      </div>
                      <p className="mt-1 text-[12px] leading-relaxed text-ink-muted">{entry.reason}</p>
                    </div>
                  </li>
                );
              })}
            </ul>
          </div>
        );
      })}
    </Panel>
  );
}
